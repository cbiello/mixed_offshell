   write(12,'(A)') "#  subroutine ktjet(pin,  nin, pjet, njet)"
   write(12,'(A)') "#    integer, intent(in) :: nin"
   write(12,'(A)') "#    real(dp), intent(in) :: pin(4,nin)  "
   write(12,'(A)') "#    integer, intent(out) :: njet"
   write(12,'(A)') "#    real(dp), intent(out) :: pjet(4,3)"
   write(12,'(A)') "#    real(dp) :: pti,dbi,ptj,dbj"
   write(12,'(A)') "#    real(dp) :: yi,yj,dy,d_cosphi,dphi,r12sq,dij"
   write(12,'(A)') "#    real(dp) :: dmin,rsq"
   write(12,'(A)') "#    real(dp) :: prehard(4,nin),prejet(4,nin)"
   write(12,'(A)') "#    integer :: nh,nj,ijmin(2)"
   write(12,'(A)') "#    integer :: i,j,le"
   write(12,'(A)') "#    real(dp), parameter :: ktclass = -one   ! antikt"
   write(12,'(A)') "#    real(dp), parameter :: ptjetcut = 20.0_dp"
   write(12,'(A)') "#    real(dp), parameter :: Rjet = 0.4_dp"
   write(12,'(A)') "#"
   write(12,'(A)') "#"
   write(12,'(A)') "#    rsq = Rjet**2"
   write(12,'(A)') "#"
   write(12,'(A)') "#    le = 0"
   write(12,'(A)') "#"
   write(12,'(A)') "#    njet = 0"
   write(12,'(A)') "#    pjet = zero"
   write(12,'(A)') "#"
   write(12,'(A)') "#    do i=1,nin"
   write(12,'(A)') "#       if (pin(1,i).ne.zero.and.(abs(pin(4,i)).ne.abs(pin(1,i)))) then "
   write(12,'(A)') "#          le = le+1"
   write(12,'(A)') "#          prehard(:,le) = pin(:,i)"
   write(12,'(A)') "#       endif"
   write(12,'(A)') "#    enddo"
   write(12,'(A)') "#"
   write(12,'(A)') "#    nj = 0"
   write(12,'(A)') "#    nh = le"
   write(12,'(A)') "#    prejet = zero"
   write(12,'(A)') "#"
   write(12,'(A)') "#!   recombine"
   write(12,'(A)') "#"
   write(12,'(A)') "#    do while (nh.gt.0) ! recombination loop"
   write(12,'(A)') "#"
   write(12,'(A)') "#       pti = sqrt(prehard(2,nh)**2+prehard(3,nh)**2)"
   write(12,'(A)') "#       dbi = pti**(2*ktclass)"
   write(12,'(A)') "#       dmin = dbi"
   write(12,'(A)') "#       ijmin = (/nh,0/)"
   write(12,'(A)') "#"
   write(12,'(A)') "#       do i = 1, nh-1 ! compute db, dij"
   write(12,'(A)') "#          "
   write(12,'(A)') "#          pti = sqrt(prehard(2,i)**2+prehard(3,i)**2)"
   write(12,'(A)') "#          dbi = pti**(2*ktclass)"
   write(12,'(A)') "#       "
   write(12,'(A)') "#          if (dbi.lt.dmin) then"
   write(12,'(A)') "#             dmin = dbi"
   write(12,'(A)') "#             ijmin = (/i,0/)"
   write(12,'(A)') "#          endif"
   write(12,'(A)') "#"
   write(12,'(A)') "#          do j = i+1,nh"
   write(12,'(A)') "#             ptj = sqrt(prehard(2,j)**2+prehard(3,j)**2)"
   write(12,'(A)') "#             dbj = ptj**(2*ktclass)"
   write(12,'(A)') "#"
   write(12,'(A)') "#             yi = half * log((prehard(1,i)+prehard(4,i))/(prehard(1,i)-prehard(4,i)))"
   write(12,'(A)') "#             yj = half * log((prehard(1,j)+prehard(4,j))/(prehard(1,j)-prehard(4,j)))"
   write(12,'(A)') "#"
   write(12,'(A)') "#             dy = yi-yj"
   write(12,'(A)') "#"
   write(12,'(A)') "#             ! cos(a-b) = cos(a)cos(b)+sin(a)sin(b)"
   write(12,'(A)') "#             d_cosphi = (prehard(2,i)*prehard(2,j)+prehard(3,i)*prehard(3,j))/pti/ptj"
   write(12,'(A)') "#             if (d_cosphi.gt.one) then"
   write(12,'(A)') "#                dphi = zero"
   write(12,'(A)') "#             elseif (d_cosphi.lt.-one) then"
   write(12,'(A)') "#                dphi = pi"
   write(12,'(A)') "#             else"
   write(12,'(A)') "#                dphi = acos(d_cosphi) ! 0<dphi<pi"
   write(12,'(A)') "#             endif"
   write(12,'(A)') "#             "
   write(12,'(A)') "#             r12sq = dy**2 + dphi**2"
   write(12,'(A)') "#"
   write(12,'(A)') "#             dij = min(dbi,dbj) * r12sq/rsq"
   write(12,'(A)') "#"
   write(12,'(A)') "#             if (dij.lt.dmin) then"
   write(12,'(A)') "#                dmin = dij"
   write(12,'(A)') "#                ijmin = (/min(i,j),max(i,j)/)"
   write(12,'(A)') "#             endif"
   write(12,'(A)') "#"
   write(12,'(A)') "#          enddo"
   write(12,'(A)') "#"
   write(12,'(A)') "#       enddo ! compute db, dij"
   write(12,'(A)') "#"
   write(12,'(A)') "#       if (ijmin(2).eq.0) then ! no recombination, 1 new jet candidate"
   write(12,'(A)') "#          nj = nj+1"
   write(12,'(A)') "#          prejet(:,nj) = prehard(:,ijmin(1))"
   write(12,'(A)') "#"
   write(12,'(A)') "#          do i = ijmin(1),nh-1"
   write(12,'(A)') "#             prehard(:,i) = prehard(:,i+1)"
   write(12,'(A)') "#          enddo"
   write(12,'(A)') "#"
   write(12,'(A)') "#       else ! recombine, no new jet candidates"
   write(12,'(A)') "#"
   write(12,'(A)') "#          prehard(:,ijmin(1)) = prehard(:,ijmin(1))+prehard(:,ijmin(2))"
   write(12,'(A)') "#"
   write(12,'(A)') "#          do i = ijmin(2),nh-1"
   write(12,'(A)') "#             prehard(:,i) = prehard(:,i+1)"
   write(12,'(A)') "#          enddo"
   write(12,'(A)') "#"
   write(12,'(A)') "#       endif"
   write(12,'(A)') "#"
   write(12,'(A)') "#       nh = nh - 1"
   write(12,'(A)') "#"
   write(12,'(A)') "#    enddo ! recombination loop"
   write(12,'(A)') "#    "
   write(12,'(A)') "#"
   write(12,'(A)') "#    do i = 1, nj"
   write(12,'(A)') "#       pti = sqrt(prejet(2,i)**2+prejet(3,i)**2)"
   write(12,'(A)') "#       if (pti.gt.ptjetcut) then"
   write(12,'(A)') "#          njet = njet + 1"
   write(12,'(A)') "#          pjet(:,njet) = prejet(:,i)"
   write(12,'(A)') "#       endif"
   write(12,'(A)') "#"
   write(12,'(A)') "#    enddo"
   write(12,'(A)') "#"
   write(12,'(A)') "#    return"
   write(12,'(A)') "#"
   write(12,'(A)') "#"
   write(12,'(A)') "#  end subroutine ktjet"
   write(12,'(A)') "#"
